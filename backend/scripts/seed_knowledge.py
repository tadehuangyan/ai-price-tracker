def main():
    Base.metadata.create_all(bind=engine)
    db = SessionLocal()
    added = 0
    try:
        for a in ARTICLES:
            exists = db.query(KnowledgeArticle).filter(KnowledgeArticle.title == a["title"]).first()
            if exists:
                continue
            db.add(KnowledgeArticle(**a))
            added += 1
        db.commit()
        total = db.query(KnowledgeArticle).count()
        print(f"知识库种子完成：新增 {added} 条，当前共 {total} 条")
    finally:
        db.close()


if __name__ == "__main__":
    main()
